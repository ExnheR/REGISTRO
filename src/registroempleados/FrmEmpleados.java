private void RefrescarTabla() {

    DefaultTableModel modelo =
            (DefaultTableModel) tbregistro.getModel();

    modelo.setRowCount(0);

    for (Empleados empleado : listaAlumnos) {

        Object[] fila = {
            empleado.getNombre(),
            empleado.getDocumento(),
            empleado.getCargo(),
            empleado.getArea(),
            empleado.getSalario()
        };

        modelo.addRow(fila);
    }
}

private void LimpiarFormulario() {

    txtnombre.setText("");
    intdocumento.setText("");
    cmbcargo.setSelectedIndex(0);
    cmbarea.setSelectedIndex(0);
    spnsalario.setValue(0);
    txtfecha.setText("");

}

