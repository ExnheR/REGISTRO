    private void btnguardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnguardarActionPerformed
  try {

        String nombre = txtnombre.getText().trim();
        String documentoTexto = intdocumento.getText().trim();
        String fecha = txtfecha.getText().trim();

        if (nombre.isEmpty() || documentoTexto.isEmpty() || fecha.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Todos los campos son obligatorios");
            return;
        }

        int documento = Integer.parseInt(documentoTexto);

        double salario = Double.parseDouble(
                spnsalario.getValue().toString()
        );

        if (salario <= 0) {
            JOptionPane.showMessageDialog(this,
                    "El salario debe ser mayor a 0");
            return;
        }

        Empleados empleado = new Empleados();

        empleado.setNombre(nombre);
        empleado.setDocumento(documento);
        empleado.setCargo(cmbcargo.getSelectedItem().toString());
        empleado.setArea(cmbarea.getSelectedItem().toString());
        empleado.setSalario(salario);
        empleado.setFechaI(fecha);

        listaAlumnos.add(empleado);

        RefrescarTabla();
        LimpiarFormulario();

        JOptionPane.showMessageDialog(this,
                "Empleado registrado correctamente");

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "El documento debe contener 10 digitos como maximo");

    }
    }//GEN-LAST:event_btnguardarActionPerformed

