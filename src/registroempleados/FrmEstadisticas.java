    private void btnpromedioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnpromedioActionPerformed
    
    if (listaAlumnos.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "No hay empleados registrados");
    return;
}

double suma = 0;

for (Empleados empleado : listaAlumnos) {
    suma += empleado.getSalario();
}

double promedio = suma / listaAlumnos.size();

JOptionPane.showMessageDialog(this,
        "El promedio salarial es: $"
        + String.format("%.2f", promedio));
// TODO add your handling code here:
    }//GEN-LAST:event_btnpromedioActionPerformed

    private void btnmayorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnmayorActionPerformed

        if (listaAlumnos.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "No hay empleados registrados");
    return;
}

Empleados mayor = listaAlumnos.get(0);

for (Empleados empleado : listaAlumnos) {
    if (empleado.getSalario() > mayor.getSalario()) {
        mayor = empleado;
    }
}

JOptionPane.showMessageDialog(this,
        "Empleado con mayor salario:\n"
        + "Nombre: " + mayor.getNombre() + "\n"
        + "Documento: " + mayor.getDocumento() + "\n"
        + "Salario: $" + mayor.getSalario());
        // TODO add your handling code here:
    }//GEN-LAST:event_btnmayorActionPerformed

